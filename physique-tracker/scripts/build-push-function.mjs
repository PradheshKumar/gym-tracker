// Builds supabase/functions/send-reminders/index.ts from the app's own reminder rules
// (src/lib/reminders.ts), the VAPID public key (src/push-key.ts) and scripts/push-handler.ts.
// Run: node scripts/build-push-function.mjs   (a test fails if the output is stale)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const app = resolve(here, '..');
export const OUT = resolve(app, '../supabase/functions/send-reminders/index.ts');

export function buildPushFunction() {
  const rules = readFileSync(resolve(app, 'src/lib/reminders.ts'), 'utf8');
  const key = readFileSync(resolve(app, 'src/push-key.ts'), 'utf8').match(/VAPID_PUBLIC_KEY = '([^']*)'/)?.[1] ?? '';
  const handler = readFileSync(resolve(app, 'scripts/push-handler.ts'), 'utf8');
  return [
    '// GENERATED by physique-tracker/scripts/build-push-function.mjs. Do not edit by hand.',
    "import webpush from 'npm:web-push@3.6.7';",
    "import { createClient } from 'npm:@supabase/supabase-js@2.45.4';",
    '',
    `const VAPID_PUBLIC_KEY = '${key}';`,
    '',
    '// ---- src/lib/reminders.ts ----',
    rules.trim(),
    '',
    '// ---- scripts/push-handler.ts ----',
    handler.trim(),
    '',
  ]
    .join('\n')
    .replace(/\r\n/g, '\n');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(OUT, buildPushFunction());
  console.log(`wrote ${OUT}`);
}
